// Helper to convert an active scheduled job booking into a live production record
export function convertBookingToProductionRecord(
  booking: JobBooking,
  sNo: number
): ProductionRecord {
  const planQty = booking.quantity || 100;
  const goodQty = booking.producedGoodQty || 0;
  const ngQty = booking.producedNgQty || 0;
  const achievedQty = goodQty + ngQty;
  const achievedPercent = planQty > 0 ? Math.round((achievedQty / planQty) * 100) : 0;

  return {
    id: `prod-sync-${booking.id}`,
    sNo,
    machineCode: booking.machineCode,
    machineName: `${booking.machineCode} Active Production Bender`,
    workOrderDate: booking.date || new Date().toLocaleDateString(),
    workOrderNo: booking.woNumber,
    customerName: booking.customer,
    assemblyPartCode: "ASSY-GEN-100",
    assemblyPartName: `${booking.woNumber} Assembly Component Batch`,
    childPartCode: booking.componentCode,
    childPartName: booking.componentName,
    planQty,
    achievedQty,
    achievedPercent,
    okQty: goodQty,
    ngQty,
    postStatus: achievedPercent >= 100 ? "pending_qc" : "draft",
    process: "Brazing",
    moveStatus: "pending",
    stdCycleTimeSec: 35.0,
    ratePerHour: 100,
    oee: {
      availability: 95.0,
      performance: achievedPercent > 0 ? Math.min(100, achievedPercent) : 85.0,
      quality: achievedQty > 0 ? Number(((goodQty / achievedQty) * 100).toFixed(1)) : 100.0,
      oee: Number(((95 * Math.min(100, achievedPercent || 85) * (achievedQty > 0 ? (goodQty / achievedQty) : 1)) / 100).toFixed(1)),
    },
    machineStatus: booking.status === "running" ? "running" : "available",
    isLiveActive: true,
    verificationStatus: "pending_verification",
    operatorName: booking.operatorName,
    operatorId: booking.operatorId,
  };
}
